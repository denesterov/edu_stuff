s = open('t24-28765.txt').read()
N = 180
# s = 'BC11111BC23BC23BC8888BC55555555555555BC'
# N = 3

b, e, c = 0, 0, 0
ms = ''
while e < len(s) or c > N: # Продолжаем, пока не достигли правой границы или все еще перебор в счетчике
    if c <= N and e < len(s): # Двигаем правый край, если еще не набрали нужного числа
        e += 1
        if s[e-2:e] == 'BC':
            c += 1
    if c <= N and e - b > len(ms): # Если выполнено условие на подсчет, ищем наш максимум/минимум
        ms = s[b:e]
    if c > N: # Двигаем левый край, если перебрали счетчик
        if s[b:b+2] == 'BC':
            c -= 1
        b += 1

print(ms, len(ms))
